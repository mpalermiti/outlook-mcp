"""Regenerate ``src/outlook_mcp/_windows_zones.py`` from CLDR's ``windowsZones.xml``.

A dev-time tool, never run by the server. Pick the CLDR commit to take it from
(the latest one that changed the file, say), download the file *at that commit*
into an empty directory of its own, and pass both:

    SHA=<40-hex CLDR commit>
    curl -sSf -o "$DIR/windowsZones.xml" \\
        "https://raw.githubusercontent.com/unicode-org/cldr/$SHA/common/supplemental/windowsZones.xml"
    uv run python -I scripts/generate_windows_zones.py "$DIR/windowsZones.xml" --cldr-commit "$SHA"

The header records that commit's URL and the file's SHA-256, so the pair can be
checked later.

The download is treated as untrusted: it is parsed with ``defusedxml`` (the
``documents`` extra, so ``uv sync --all-extras`` first), and every name and
zone must match a plain-text pattern before it is written into Python source.
Only the ``territory="001"`` rows are kept: CLDR's one default zone per
Windows name.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "outlook_mcp" / "_windows_zones.py"
SOURCE_URL = "https://raw.githubusercontent.com/unicode-org/cldr/{commit}/common/supplemental/windowsZones.xml"
# CLDR has had over 130 Windows names for years; fewer means a broken file.
# `tests/test_windows_zones.py` holds the table to the same floor.
MIN_ROWS = 130

# What a Windows zone name and an IANA key look like. Anything else is refused
# rather than escaped: the values are written into a Python module.
_WINDOWS_NAME = re.compile(r"[A-Za-z0-9 .()+\-]{1,64}")
_IANA_KEY = re.compile(r"[A-Za-z0-9_+\-]+(?:/[A-Za-z0-9_+\-]+){0,2}")
_COMMIT = re.compile(r"[0-9a-f]{40}")


def parse(xml_bytes: bytes) -> tuple[dict[str, str], str, str]:
    """``{windows name: IANA key}`` for the 001 rows, and the file's two versions."""
    # Here, not at the top: the tests import MIN_ROWS without the `documents` extra.
    from defusedxml import ElementTree

    root = ElementTree.fromstring(xml_bytes)
    table = root.find("windowsZones/mapTimezones")
    if table is None:
        raise SystemExit("no windowsZones/mapTimezones element: not CLDR's windowsZones.xml")
    mapping: dict[str, str] = {}
    for row in table.iter("mapZone"):
        if row.get("territory") != "001":
            continue
        name, zone = row.get("other", ""), row.get("type", "")
        if not _WINDOWS_NAME.fullmatch(name) or not _IANA_KEY.fullmatch(zone):
            raise SystemExit(f"refusing an unexpected row: other={name!r} type={zone!r}")
        if name in mapping:
            raise SystemExit(f"two 001 rows for {name!r}")
        mapping[name] = zone
    if len(mapping) < MIN_ROWS:
        raise SystemExit(f"only {len(mapping)} rows; expected at least {MIN_ROWS}")
    versions = (table.get("typeVersion", "?"), table.get("otherVersion", "?"))
    for version in versions:
        if not re.fullmatch(r"[A-Za-z0-9.?]{1,16}", version):
            raise SystemExit(f"refusing an unexpected version attribute: {version!r}")
    return mapping, versions[0], versions[1]


def render(
    mapping: dict[str, str], tz_version: str, windows_version: str, commit: str, sha256: str
) -> str:
    rows = "\n".join(f'    "{name}": "{zone}",' for name, zone in sorted(mapping.items()))
    return f'''"""Windows time zone names to IANA keys, to convert a moment into an event's zone.

GENERATED by ``scripts/generate_windows_zones.py``; do not edit by hand.
Source: CLDR ``common/supplemental/windowsZones.xml``, ``territory="001"`` rows
(CLDR's default zone for each Windows name).
  URL: {SOURCE_URL.format(commit=commit)}
  CLDR commit: {commit}
  File SHA-256: {sha256}
  tzdata version (typeVersion): {tz_version}; Windows version (otherVersion): {windows_version}

Graph names an event's zone in Windows terms ("Pacific Standard Time") for
anything it was not handed an IANA name for (#236). Used only to *convert*;
the name sent back to Graph is always the one Graph gave.
"""

WINDOWS_TO_IANA: dict[str, str] = {{
{rows}
}}
'''


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("xml", type=Path, help="path to the downloaded windowsZones.xml")
    parser.add_argument("--cldr-commit", required=True, help="CLDR commit the file came from")
    args = parser.parse_args(argv)
    if not _COMMIT.fullmatch(args.cldr_commit):
        raise SystemExit("--cldr-commit must be a 40-character hex sha")

    data = args.xml.read_bytes()
    mapping, tz_version, windows_version = parse(data)
    module = render(
        mapping, tz_version, windows_version, args.cldr_commit, hashlib.sha256(data).hexdigest()
    )
    OUTPUT.write_text(module, encoding="utf-8")
    print(f"wrote {len(mapping)} names to {OUTPUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
